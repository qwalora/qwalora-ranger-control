#!/usr/bin/env bash
# STRATA S5.1 CI evidence collector. Writes SANITIZED validation evidence into artifacts/ for audit.
# Best-effort: never fails the job (the JUnit gate governs pass/fail). Never prints or writes the
# admin password, scenario seeds, hidden grading truth, or signing keys.
set -uo pipefail

URL="${RANGER_TEST_OPENSEARCH_URL:-https://127.0.0.1:9200}"
USER="${RANGER_TEST_OPENSEARCH_USER:-admin}"
PW="${OPENSEARCH_INITIAL_ADMIN_PASSWORD:-${RANGER_TEST_OPENSEARCH_PASSWORD:-}}"
OUT="artifacts"
mkdir -p "$OUT"
SUMMARY="$OUT/evidence-summary.md"

# curl helper (admin). Credentials are passed via -u but never echoed to the log or files.
q() { curl -sk -u "${USER}:${PW}" "${URL}$1"; }

{
  echo "# STRATA S5.1 real-OpenSearch evidence"
  echo
  echo "## Node identity"
  root="$(q / 2>/dev/null || true)"
  dist="$(printf '%s' "$root" | sed -n 's/.*"distribution"[ ]*:[ ]*"\([^"]*\)".*/\1/p' | head -1)"
  ver="$(printf '%s'  "$root" | sed -n 's/.*"number"[ ]*:[ ]*"\([^"]*\)".*/\1/p' | head -1)"
  echo "- distribution: ${dist:-unknown}"
  echo "- version: ${ver:-unknown}"
  echo
  echo "## Security plugin"
  sec="$(q /_plugins/_security/health 2>/dev/null || true)"
  echo "- security health: ${sec:-unavailable}"
  echo
  echo "## Cluster health"
  echo '```'
  q "/_cluster/health?pretty" 2>/dev/null || echo "unavailable"
  echo '```'
  echo
  echo "## Indices present at evidence time (after per-test teardown)"
  echo '```'
  q "/_cat/indices?v&expand_wildcards=all" 2>/dev/null || echo "unavailable"
  echo '```'
  echo
  echo "_Generated by ci_evidence.sh. Credentials, seeds, grading truth and signing keys are never"
  echo "included. Per-run qualification indices are cleaned up by the suite's teardown, so only"
  echo "system indices and the sentinel are expected to remain here._"
} > "$SUMMARY" 2>/dev/null || true

# Also surface the node identity + security status into the GitHub step summary when available.
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
  {
    echo "### Real node"
    echo "- distribution: ${dist:-unknown}  version: ${ver:-unknown}"
    echo "- security health: ${sec:-unavailable}"
  } >> "$GITHUB_STEP_SUMMARY" 2>/dev/null || true
fi
echo "evidence written to $SUMMARY"
exit 0
